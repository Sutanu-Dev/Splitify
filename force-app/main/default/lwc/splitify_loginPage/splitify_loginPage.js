import {NavigationMixin} from 'lightning/navigation';
import login from '@salesforce/apex/splitify_service.login'
import signUp from '@salesforce/apex/splitify_service.signUp'
import sendEmail from '@salesforce/apex/GmailService.sendEmail';
import forgotPasswordHandler from '@salesforce/apex/splitify_service.forgotPasswordHandler';
import duplicateEmailVerification from '@salesforce/apex/splitify_service.duplicateEmailVerification';
import addToGroup from '@salesforce/apex/splitify_service.addToGroup';

