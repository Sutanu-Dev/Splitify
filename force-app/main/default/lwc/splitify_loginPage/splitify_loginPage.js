    showLoginErrorMessage = false;
    showSignUpErrorMessage = false;
    showSignUpErrorForEmail = false;
    showVerificationErrorMessage = false;
    showForgotPasswordErrorForEmail = false;
    showForgotPasswordErrorForCode = false;
