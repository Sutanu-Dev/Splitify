    addToInvitedGroup(groupId, userId){
        addToGroup({GroupId : groupId, UserId: userId})
        .then(() => {
            localStorage.removeItem('inviteId');
            this.navigateToHomePage();
        })
        .catch((error) => {
            this.showError = error.body.exceptionType + ' : '+ error.body.message;
            console.error('error while adding user to group : ',error);
        })
    }

    navigateToHomePage(){
        this[NavigationMixin.Navigate]({

            type: 'comm__namedPage',
            attributes: {
                name: 'Home'
            },
            state : {}
        })
    }

    showSignUpPage(){
            const signUpPage = this.template.querySelector('.signup-container');
            const loginPage = this.template.querySelector('.login-container');

            loginPage.style.height = '3.3rem';
            loginPage.style.padding = '0.5rem';
            signUpPage.style.height = '26rem';
            signUpPage.style.padding = '3rem 2rem';
            
    }

    showLoginPage(){
            const loginPage = this.template.querySelector('.login-container');
            const signUpPage = this.template.querySelector('.signup-container');

            loginPage.style.height = '22rem';
            loginPage.style.padding = '3rem 2rem';
            signUpPage.style.height = '3.3rem';
            signUpPage.style.padding = '0rem';
    }

    generateSixDigitRandomNumber() {
        this.autoGeneratedCode = Math.floor(100000 + Math.random() * 900000);
        return this.autoGeneratedCode;
    }

    handleForgotPassword(event){
        this.template.querySelector('.login').style.translate = '-120%';
        this.template.querySelector('.forgot-password-container').style.translate = '0%';
    }

    //forgot password container logic

    goBackToLoginComponent(event){
        this.template.querySelector('.login').style.translate = '0%'
        this.template.querySelector('.forgot-password-container').style.translate = '120%';
    }

    forgotPasswordEmailHandler(event){
        event.preventDefault();
        this.showForgotPasswordErrorForEmail = false;

        this.isLoading = true;
        const forgotPasswordCodeForm = this.template.querySelector('.forgot-password-code-form');
        const email = event.target.email.value.trim();
        const forgotPasswordEmailFormEl = event.currentTarget;

        forgotPasswordHandler({Email: email, Password: ''})
        .then((data) => {
            if(data === 'true'){
                this.isLoading = false;
                
                forgotPasswordEmailFormEl.style.translate = "-120%";
                forgotPasswordCodeForm.style.translate = '0%';

                const sixDigitString = this.generateSixDigitRandomNumber().toString();
                
                sendEmail({toEmail : email, contentBody : sixDigitString, Heading: 'Reset Password'})
                .then(() => {
                })
                .catch(error => {

                })
            }
        })
        .catch((error) => {
            this.showForgotPasswordErrorForEmail = true;
            this.isLoading = false;
        }) 
    }
    goBackToForgotPasswordEmail(){
        this.template.querySelector('.forgot-password-code-form').style.translate = '120%';
        this.template.querySelector('.forgot-password-email').style.translate = '0%';
    }

    forgotPasswordCodeHandler(event){
        event.preventDefault();
        this.showForgotPasswordErrorForCode = false;
        this.isLoading = true;
        const code = event.target.forgotPasswordCode.value.trim();

        if(code != this.autoGeneratedCode){
            this.showForgotPasswordErrorForCode = true;
            this.isLoading = false;
            return;
        }
        const newPasswordForm = this.template.querySelector('.new-password-form');
        this.isLoading = false;
        event.currentTarget.style.translate = "-120%";
        newPasswordForm.style.translate = '0%';
    }

    goBackToLoginComponent(){
        this.template.querySelector('.forgot-password-container').style.translate = '120%';
        this.template.querySelector('.login').style.translate = '0%';
        const newPasswordForm = this.template.querySelector('.new-password-form');
        const forgotPasswordCodeForm = this.template.querySelector('.forgot-password-code-form');
        const forgotPasswordEmailForm = this.template.querySelector('.forgot-password-email');
        forgotPasswordEmailForm.style.translate = '0%';
        newPasswordForm.style.translate = '120%';
        forgotPasswordCodeForm.style.translate = '120%';
        forgotPasswordEmailForm.reset();
        newPasswordForm.reset();
        forgotPasswordCodeForm.reset();
    }
    
    newPasswordHandler(event){
        event.preventDefault();
        this.showNewPasswordError = false;
        this.isLoading = true;
        const email = this.template.querySelector('.forgot-password-email').email.value.trim();
        const newPassword = event.target.newPassword.value.trim();
        const newConfirmPassword = event.target.newConfirmPassword.value.trim();
        if(newPassword !== newConfirmPassword){
            this.showNewPasswordError = true;
            this.isLoading = false;
            return;
        }

         forgotPasswordHandler({Email: email, Password: newPassword})
        .then((data) => {
            const toast = this.template.querySelector('c-custom-toast');
            toast.show('Password Changed! Please Login.', 'success');
            this.isLoading = false;

            localStorage.setItem('userId', data);
            this.goBackToLoginComponent();
        })
        .catch((error) => {
            const toast = this.template.querySelector('c-custom-toast');
            toast.show(error, 'error');
        })
    }
    
