    isLoading = false;
    autoGeneratedCode;


    renderedCallback(){
       
    }

    handleLogin(event){
        event.preventDefault()
        this.isLoading = true;
        this.showLoginErrorMessage = false;

        const email = event.target.email.value.trim();
        const password = event.target.password.value.trim();

        login({Email: email, Password: password})
        .then((data) => {
            if(data == null || data === 'error'){
                this.isLoading = false;
                this.showLoginErrorMessage = true;
                return;
            }
            localStorage.setItem('userId', data);
            localStorage.setItem('refresh', 'true');

            this[NavigationMixin.Navigate]({

                type: 'comm__namedPage',
                attributes: {
                    name: 'Home'
                },
                state : {
                    // "userId" : "12345abcd"
                }
            })
            this.isLoading = false;
        })
        .catch(error => {
            this.isLoading = false;
            this.showLoginErrorMessage = true;

        })
        
        
    }

    handleSignUp(event){
        event.preventDefault();
        this.isLoading = true;
        this.showSignUpErrorForEmail = false;
        this.showSignUpErrorMessage = false;

        // const signupEl = this.template.querySelector('.signup');
        // const verificationEl = this.template.querySelector('.verification');

        const fullName = event.target.name.value.trim().split(' ').filter(word => word != '').join(' ');
        const email = event.target.email.value.trim();
        const password = event.target.password.value.trim();
        const confirmPassword = event.target.confirmPassword.value.trim();

        if(password !== confirmPassword){
            this.showSignUpErrorMessage = true;
            this.isLoading = false;
            return;
        }

        duplicateEmailVerification({Email: email})
        .then((data) => {
            if(data === "email exist"){
                this.showSignUpErrorForEmail = true;
                return Promise.reject('Email already exists');
            }

            signUp({Fullname: fullName, Email: email, Password: password})
            .then((data) => {

                localStorage.setItem('userId', data);
                localStorage.setItem('refresh', 'true');

                const inviteId = localStorage.getItem('inviteId');
                if(inviteId){
                    this.addToInvitedGroup(inviteId, data);
                    this.isLoading = false;
                    return;
                }

                this.navigateToHomePage();
                this.isLoading = false;
            })
            .catch(error => {
                console.error('error while signing up  :', error);
            })
            //const verificationCode  = this.generateSixDigitRandomNumber().toString();
            //return sendEmail({ toEmail: email, contentBody: verificationCode, Heading: 'Splitify' });
        })
        // .then (() => {
        //     this.transitionToVerification(signupEl,verificationEl);
        // })
        .catch((error) => {
            console.error('error', error);
        })
        .finally(() => {
            this.isLoading = false;
        })

        //sign up user creation
        
    }

